const assignGlobalLessonNumbers = (curriculum) => {
  let nextLessonNumber = 1;

  curriculum.levels.forEach((level) => {
    level.modules.forEach((module) => {
      module.lessons.forEach((lesson) => {
        lesson.lesson_number = nextLessonNumber;
        nextLessonNumber += 1;
      });
    });
  });

  return curriculum;
};

